// ── 출제 ────────────────────────────────────────────────────────────────
//
// 1) 후보(Candidate) 목록을 만든다 — 지식 파생 양방향 + 단발 문항.
// 2) 이력(SeenMap)을 보고 고른다 — 안 본 것 우선 → 모자라면 오래 전에 본 것부터.
// 3) 고른 후보를 문제로 만든다 — 이때 오답을 뽑고 보기를 셔플한다.

/** 보기 셔플 전의 문제. 정답은 인덱스가 아니라 문자열로 들고 있다. */
type RawQuestion = { q: string; ans: string; d: string[] };

/** 지연 생성 후보. make() 는 호출될 때마다 오답을 새로 뽑는다. */
export type Candidate = { qid: string; source: string; make: () => RawQuestion };

/** qid → 마지막으로 출제된 시각(epoch ms). 없는 키 = 아직 본 적 없음. */
export type SeenMap = Record<string, number>;

/** 같은 권역 풀이 이만큼 안 되면 오답을 전체 풀에서 뽑는다. */
const NEAR_POOL_MIN = 4;

/**
 * 오답 n개를 뽑는다. 가까운 풀(같은 권역·같은 카테고리) 우선, 모자라면 전체 풀로 보충.
 * 정답과 같은 값, 중복은 제외한다.
 */
function pickDistractors(ans: string, near: readonly string[], all: readonly string[], n = 3): string[] {
  const pool = (xs: readonly string[]) => Array.from(new Set(xs)).filter((x) => x !== ans);
  const out = shuffle(pool(near)).slice(0, n);
  if (out.length < n) {
    const rest = shuffle(pool(all)).filter((x) => !out.includes(x));
    out.push(...rest.slice(0, n - out.length));
  }
  return out;
}

/**
 * 1:1 로 대응하는 지식 테이블에서 양방향 후보를 만든다.
 *
 * 테이블마다 같은 코드를 복붙하던 것을 하나로 합쳤다 — 테이블이 7개가 되면서
 * 복붙이 유지보수 부담이 됐고, 오답 풀을 잘못 넘기는 실수가 나기 쉬웠다.
 *
 * near 를 주면 오답을 그 좁은 풀에서 먼저 뽑는다(수도의 권역처럼).
 * 풀이 모자라면 전체 테이블로 보충한다.
 */
function pairCandidates<T>(opts: {
  /** source 접두사. qid 가 여기서 나오므로 한번 정하면 바꾸지 말 것. */
  prefix: string;
  items: readonly T[];
  /** source 키가 될 값 (보통 왼쪽 값) */
  key: (t: T) => string;
  left: (t: T) => string;
  right: (t: T) => string;
  /** 왼쪽을 보여주고 오른쪽을 묻는 문구 */
  askRight: (t: T) => string;
  /** 오른쪽을 보여주고 왼쪽을 묻는 문구 */
  askLeft: (t: T) => string;
  near?: (t: T) => readonly T[];
}): Candidate[] {
  const { prefix, items, key, left, right, askRight, askLeft, near } = opts;
  const allLeft = items.map(left);
  const allRight = items.map(right);

  return items.flatMap((t) => {
    const pool = near ? near(t) : items;
    const source = `${prefix}:${key(t)}`;
    return [
      {
        qid: `${source}:fwd`,
        source,
        make: () => ({
          q: askRight(t),
          ans: right(t),
          d: pickDistractors(right(t), pool.map(right), allRight),
        }),
      },
      {
        qid: `${source}:rev`,
        source,
        make: () => ({
          q: askLeft(t),
          ans: left(t),
          d: pickDistractors(left(t), pool.map(left), allLeft),
        }),
      },
    ];
  });
}

/** 지식 테이블 7종. 한 줄 추가 = 문제 2개. */
function factCandidates(): Candidate[] {
  return [
    ...pairCandidates({
      prefix: "cap",
      items: CAPITALS,
      key: (c) => c.country,
      left: (c) => c.country,
      right: (c) => c.capital,
      askRight: (c) => `${c.country}의 수도는 어디일까요?`,
      askLeft: (c) => `${c.capital} — 어느 나라의 수도일까요?`,
      // 같은 권역에서 오답을 뽑아야 난이도가 산다. 아무 대륙 수도를 섞으면
      // 내용을 몰라도 소거법으로 맞힌다.
      near: (c) => {
        const region = CAPITALS.filter((x) => x.region === c.region);
        return region.length >= NEAR_POOL_MIN ? region : CAPITALS;
      },
    }),
    ...pairCandidates({
      prefix: "idiom",
      items: IDIOMS,
      key: (i) => i.idiom,
      left: (i) => i.idiom,
      right: (i) => i.meaning,
      askRight: (i) => `'${i.idiom}'의 뜻은?`,
      askLeft: (i) => `'${i.meaning}' — 이 뜻의 한자성어는?`,
    }),
    ...pairCandidates({
      prefix: "season",
      items: SEASONAL,
      key: (s) => s.occasion,
      left: (s) => s.occasion,
      right: (s) => s.food,
      askRight: (s) => `${s.occasion}에 먹는 대표 음식은?`,
      askLeft: (s) => `${s.food} — 언제 먹는 음식일까요?`,
    }),
    ...pairCandidates({
      prefix: "term",
      items: SOLAR_TERMS,
      key: (t) => t.term,
      left: (t) => t.term,
      right: (t) => t.meaning,
      askRight: (t) => `절기 '${t.term}'은 어떤 날일까요?`,
      askLeft: (t) => `'${t.meaning}' — 이 절기의 이름은?`,
    }),
    ...pairCandidates({
      prefix: "animal",
      items: ANIMALS,
      key: (a) => a.animal,
      left: (a) => a.animal,
      right: (a) => a.baby,
      askRight: (a) => `${a.animal}의 새끼를 무엇이라고 부를까요?`,
      askLeft: (a) => `'${a.baby}' — 어떤 동물의 새끼일까요?`,
    }),
    ...pairCandidates({
      prefix: "body",
      items: BODY_PARTS,
      key: (b) => b.part,
      left: (b) => b.part,
      right: (b) => b.work,
      askRight: (b) => `우리 몸에서 '${b.part}'가 하는 일은?`,
      askLeft: (b) => `'${b.work}' — 우리 몸의 어디일까요?`,
    }),
    ...pairCandidates({
      prefix: "unit",
      items: OLD_UNITS,
      key: (u) => u.unit,
      left: (u) => u.unit,
      right: (u) => u.size,
      askRight: (u) => `'${u.unit}'은 얼마쯤일까요?`,
      askLeft: (u) => `'${u.size}' — 옛 단위로 얼마일까요?`,
    }),
  ];
}

/** 상식 퀴즈 후보 — 지식 파생 + 단발 문항. */
export function quizCandidates(): Candidate[] {
  const statics: Candidate[] = QUIZ.map((item) => ({
    qid: `quiz:${item.id}`,
    source: `quiz:${item.id}`,
    make: () => ({
      q: item.q,
      ans: item.o[item.a],
      d: item.o.filter((_, i) => i !== item.a),
    }),
  }));
  return [...factCandidates(), ...statics];
}

/**
 * 단어 맞추기 후보.
 *
 * 오답(d)은 문항마다 손으로 골라 둔다. 퀴즈처럼 같은 카테고리 풀에서 무작위로
 * 뽑으면 안 된다 — 연상 게임이라 "연필"에 "종이" 같은, 정답과 똑같이 그럴듯한
 * 오답이 섞여 정답이 두 개가 되어 버린다.
 *
 * 은행 크기가 하루 소비량(하드 12문제 × 2판 = 24)을 넘어야 회전이 의미를 갖는다.
 */
export function wordCandidates(): Candidate[] {
  return WORDQ.map((w) => ({
    qid: `word:${w.id}`,
    source: `word:${w.id}`,
    make: () => ({ q: w.q, ans: w.ans, d: w.d }),
  }));
}

export function candidatesFor(gameId: ChoiceGameId): Candidate[] {
  return gameId === "quiz" ? quizCandidates() : wordCandidates();
}

/**
 * 안 본 문제 우선 → 모자라면 오래 전에 본 것부터 n개 고른다.
 * 한 판 안에서 같은 source 는 한 번만 쓴다(같은 지식의 양방향 동시 출제 = 답 유출).
 *
 * 이력이 같은 시각인 문제들은 shuffle 한 뒤 안정 정렬로 순서를 흩는다 —
 * 안 그러면 회전 주기마다 같은 순서가 반복된다.
 */
export function selectCandidates(pool: readonly Candidate[], n: number, seen: SeenMap): Candidate[] {
  const unseen: Candidate[] = [];
  const already: Candidate[] = [];
  for (const c of pool) (seen[c.qid] === undefined ? unseen : already).push(c);

  const ordered = [
    ...shuffle(unseen),
    ...shuffle(already).sort((a, b) => seen[a.qid] - seen[b.qid]),
  ];

  const usedSource = new Set<string>();
  const out: Candidate[] = [];
  for (const c of ordered) {
    if (out.length >= n) break;
    if (usedSource.has(c.source)) continue;
    usedSource.add(c.source);
    out.push(c);
  }
  return out;
}

/** 출제 결과. qid 는 이력 기록용으로 서버에만 남기고 클라에는 ChoiceRound 만 내린다. */
export type ServedRound = ChoiceRound & { qid: string };

export function buildRounds(gameId: ChoiceGameId, n: number, seen: SeenMap = {}): ServedRound[] {
  return selectCandidates(candidatesFor(gameId), n, seen).map((c) => {
    const raw = c.make();
    const options = shuffle([raw.ans, ...raw.d]);
    return { qid: c.qid, prompt: raw.q, options, answer: options.indexOf(raw.ans) };
  });
}
