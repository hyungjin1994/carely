-- 0023: 자녀 호칭(family_links.child_label).
--
-- 왜: 회상 질문에 자녀 이름이 그대로 박혀 있었다("형진이가 좋아하는 음식이 뭘까요?").
-- 이 앱은 부모님이 사용자, 자녀가 관리자인 구조이므로 **관리자가 호칭을 정하고
-- 어머니 화면에는 그 호칭이 나오는 것**이 맞다. 다른 가족이 써도 그대로 동작한다.
--
-- 질문 문구에는 `{자녀}` 자리표시자를 쓰고 출제할 때 바꿔 넣는다(lib/korean.ts).
-- 조사는 받침 유무로 갈리므로 문구에 조사 쌍을 적어 둔다.
--   "{자녀}이/가 좋아하는 음식이 뭘까요?"
--     child_label = '형진이' → "형진이가 좋아하는 음식이 뭘까요?"
--     child_label = '아들'   → "아들이 좋아하는 음식이 뭘까요?"
--
-- 비어 있으면 관리자 이름(profiles.name)을 쓰고, 그것도 없으면 "아이" 로 채운다.
-- 이름을 그대로 쓰면 "형진 좋아하는" 처럼 읽혀 어색하므로, 관리자가 "형진이" 로
-- 적을 수 있게 별칭 칸을 따로 둔 것이다.

alter table public.family_links
  add column if not exists child_label text;

comment on column public.family_links.child_label is
  '어머니 화면에 보일 자녀 호칭. 읽히는 그대로 적는다(형진이·아들·큰딸). 조사는 앱이 고른다.';
